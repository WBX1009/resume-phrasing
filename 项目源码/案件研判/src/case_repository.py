"""Server-owned, versioned case inputs. API callers cannot grant themselves scope."""
from __future__ import annotations

from collections.abc import Mapping
import json
from pathlib import Path
import re
from typing import Any, Protocol

from pydantic import Field, model_validator

from .case_execution import CaseTaskScope, PlanError
from .investigation_contracts import Contract, authorize_bounds, stable_id


class SourceRecord(Contract):
    row_id: str | int
    entity_ids: list[str] = Field(min_length=1)
    occurred_at: str
    data: dict[str, Any]


class CaseModel(Contract):
    model_id: int = Field(gt=0)
    name: str
    category: str = "通用"
    records: list[SourceRecord] = Field(max_length=100_000)
    strategy: dict[str, Any] = Field(default_factory=dict)
    complete: bool = True

    @model_validator(mode="after")
    def unique_rows(self):
        keys = [str(r.row_id) for r in self.records]
        if len(keys) != len(set(keys)):
            raise ValueError("duplicate source row_id")
        return self


class CaseSnapshot(Contract):
    case_id: str = Field(min_length=1)
    entity_ids: list[str] = Field(min_length=1)
    time_range: tuple[str, str]
    allowed_tools: list[str] = Field(min_length=1)
    models: list[CaseModel] = Field(min_length=1, max_length=200)
    thresholds: dict[str, Any] = Field(default_factory=dict)
    data_label: str = "authorized_snapshot"

    @model_validator(mode="after")
    def authorized_records(self):
        ids = [m.model_id for m in self.models]
        if len(ids) != len(set(ids)):
            raise ValueError("duplicate model_id")
        scope = self.scope()
        for model in self.models:
            for row in model.records:
                authorize_bounds(row.entity_ids, (row.occurred_at, row.occurred_at), scope)
        return self

    def scope(self):
        return CaseTaskScope(frozenset(self.entity_ids), frozenset(self.allowed_tools), self.time_range)

    def reference(self):
        return stable_id("snapshot", self.model_dump(mode="json"))


class CaseRepository(Protocol):
    def load(self, case_id: str) -> CaseSnapshot: ...


class MappingCaseRepository:
    """Explicit server-side fixtures or a pre-authorized database export."""
    def __init__(self, cases: Mapping[str, Any]):
        self._cases = {key: CaseSnapshot.model_validate(value) for key, value in cases.items()}

    def load(self, case_id):
        if case_id not in self._cases:
            raise KeyError("case is not available to this repository")
        return self._cases[case_id].model_copy(deep=True)


class FileCaseRepository:
    """Read only administrator-provisioned JSON snapshots under one directory.

    A deployment must bind the repository to its authenticated user's permitted
    cases. It is not an authentication system or a client-supplied upload path.
    """
    def __init__(self, root: Path | str):
        self.root = Path(root).resolve()

    def load(self, case_id):
        if not re.fullmatch(r"[A-Za-z0-9_-]{1,100}", case_id):
            raise PlanError("invalid case identifier")
        path = (self.root / f"{case_id}.json").resolve()
        if path.parent != self.root:
            raise PlanError("case path escapes repository")
        with path.open(encoding="utf-8") as handle:
            result = CaseSnapshot.model_validate(json.load(handle))
        if result.case_id != case_id:
            raise PlanError("case identifier does not match server snapshot")
        return result


def load_snapshot(store, state) -> CaseSnapshot:
    snapshot = CaseSnapshot.model_validate(store.artifact(state["run_id"], state["snapshot_ref"]))
    if snapshot.reference() != state["snapshot_ref"] or snapshot.case_id != state["case_id"]:
        raise PlanError("snapshot integrity mismatch")
    return snapshot


class RowSourceCaseRepository:
    """Connect the existing parameterized DbRowSource to the same case graph.

    `policies` is a server-owned catalog of CaseSnapshot metadata with empty
    record arrays, not input supplied by the client or generated by a model.
    Each model strategy must declare person_fields and time_fields. Sampling,
    truncation or unparseable rows make the admitted snapshot incomplete.
    """
    def __init__(self, row_source, policies: Mapping[str, Any], *, max_rows_per_model=50_000):
        if not isinstance(max_rows_per_model, int) or max_rows_per_model <= 0:
            raise ValueError("max_rows_per_model must be positive")
        self.source, self.max_rows = row_source, max_rows_per_model
        self.policies = {key: CaseSnapshot.model_validate(value) for key,value in policies.items()}

    def load(self, case_id):
        from .row_source import RowQuery
        from .field_profile import parse_datetime
        from itertools import islice
        if case_id not in self.policies:
            raise KeyError("case is not authorized")
        policy = self.policies[case_id].model_copy(deep=True)
        for model in policy.models:
            entity_fields = model.strategy.get("person_fields", [])
            time_fields = model.strategy.get("time_fields", [])
            if not entity_fields or not time_fields:
                raise PlanError("database model needs explicit entity and time field mappings")
            query = RowQuery(any_field_equals=tuple((field,e) for field in entity_fields for e in policy.entity_ids),
                limit=self.max_rows+1)
            rows = list(islice(self.source.iter_model_rows_query(int(case_id), model.model_id, query), self.max_rows+1))
            complete = model.complete and self.source.source_name not in {"snapshot", "auto"} and len(rows) <= self.max_rows
            selected = []
            for row_id, payload in rows[:self.max_rows]:
                entities = sorted({str(payload[f]) for f in entity_fields if payload.get(f)})
                parsed = next((t for f in time_fields if (t := parse_datetime(payload.get(f))) is not None), None)
                if not parsed:
                    complete = False
                    continue
                try:
                    authorize_bounds(entities, (parsed.isoformat(), parsed.isoformat()), policy.scope())
                except PlanError:
                    continue
                selected.append(SourceRecord(row_id=row_id, entity_ids=entities, occurred_at=parsed.isoformat(), data=payload))
            model.records, model.complete = selected, complete
        policy.data_label = f"authorized_{self.source.source_name}_snapshot"
        return CaseSnapshot.model_validate(policy.model_dump(mode="json"))
